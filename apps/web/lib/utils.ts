import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs));
}

/**
 * Secure cookies are dropped silently by browsers served over plain HTTP, so login "succeeds"
 * and the redirect bounces straight back to /login. Default to the scheme of APP_URL; override
 * with COOKIE_SECURE when a TLS proxy sits in front of the app.
 */
export function cookieSecure(): boolean {
  const override = process.env.COOKIE_SECURE;
  if (override) return override === 'true';
  return (process.env.APP_URL ?? '').startsWith('https://');
}

export function formatBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
  const units = ['B', 'KB', 'MB', 'GB'];
  const index = Math.min(Math.floor(Math.log(bytes) / Math.log(1024)), units.length - 1);
  const value = bytes / 1024 ** index;
  return `${value >= 10 || index === 0 ? Math.round(value) : value.toFixed(1)} ${units[index]}`;
}

export function formatDuration(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds <= 0) return '0:00';
  const total = Math.round(seconds);
  const minutes = Math.floor(total / 60);
  const rest = total % 60;
  return `${minutes}:${String(rest).padStart(2, '0')}`;
}